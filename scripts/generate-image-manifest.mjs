import { readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const root = path.resolve("public/images");
const output = path.resolve("data/image-manifest.ts");
const supported = new Set([".webp", ".avif", ".jpg", ".jpeg", ".png"]);
const manifest = {};

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const images = entries
    .filter((entry) => entry.isFile() && supported.has(path.extname(entry.name).toLowerCase()))
    .sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }));

  if (images.length) {
    const relativeDirectory = path.relative(path.resolve("public"), directory).split(path.sep).join("/");
    manifest[`/${relativeDirectory}`] = images.map((entry) => `/${relativeDirectory}/${entry.name}`);
  }

  for (const entry of entries.filter((item) => item.isDirectory())) {
    await walk(path.join(directory, entry.name));
  }
}

if (existsSync(root)) await walk(root);

const source = `// Generated by scripts/generate-image-manifest.mjs. Do not edit by hand.\nexport const imageManifest: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)};\n`;
await writeFile(output, source);
console.log(`Indexed ${Object.values(manifest).flat().length} catalog images.`);
